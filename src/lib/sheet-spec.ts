/**
 * 标准图纸规范（点位图、方案、AI 识别共用）。
 *
 * 1. 户型图先裁掉图框、标题栏和图名，只保留平面图本体（含墙体、尺寸和标注）。
 * 2. 裁切结果等比放进 3:2 的白底画布：存储尺寸 2400 × 1600 px，四周留白 3.5%。
 * 3. 放进点位图时占 1200 × 800 个场景单位；打开点位图或切换图纸时，图纸正好铺满画布，
 *    这个状态就是缩放「100%」。
 * 4. AI 识别、导入点位时，坐标用相对标准图纸的比例（0–1），或标准图纸像素（2400 × 1600）。
 */
export const SHEET = {
  /** 存储像素尺寸（2 倍清晰度，打印 A4 横版仍然清晰） */
  pixelWidth: 2400,
  pixelHeight: 1600,
  /** 点位图场景尺寸 */
  width: 1200,
  height: 800,
  /** 多张图纸横向排列的间距 */
  gap: 240,
  /** 图纸标题在图纸上方的位置和字号 */
  titleOffset: 44,
  titleSize: 28,
  /** 裁切后放进标准图纸时四周的留白（短边比例） */
  padding: 0.035,
  /** 底图在画布上的不透明度：线条变浅灰，彩色点位更醒目 */
  opacity: 60,
  /** 上传文件大小上限 */
  maxUploadBytes: 12 * 1024 * 1024,
} as const

/** 第 index 张图纸在场景中的左上角 */
export const sheetOrigin = (index: number) => ({ x: index * (SHEET.width + SHEET.gap), y: 0 })

/** 点位标记规范：相对 1200 宽的图纸，图标直径 24、代号字号 9，打印和屏幕都清楚又不遮挡图纸。 */
export const MARKER = {
  size: 24,
  labelSize: 9,
  labelGap: 1,
} as const
